// Rebuild every Lexicon Realms zone module (dev tool; deterministic; never at runtime).
//
//   node tools/maps/build_world.mjs            writes src/data/maps/{willowmere,valley,downs,moor}.js,
//                                              assets/tiles/tiles.json (trimmed to the ids the zones use) and copies
//                                              the tile sheets they need from Lexicon Quest (READ ONLY source)
//
// Willowmere is Lexicon Quest's map as is (tools/dev/import_lq_maps.mjs) plus a small Realms patch (the west gate to
// the Downs, the joins, the NPC spots). The valley, the Downs and the High Moor are generated by zone_*.mjs in this
// folder: LQ's own tiles, autotiles and props, laid out by hand-placed polylines and landmarks with a little value
// noise for texture. After baking collision every spawn, NPC, node, lantern and hook is snapped onto a walkable cell
// and checked reachable on foot from the zone's arrival; a failure stops the build (BUILD_WORLD_FAIL).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LQ, loadLqDb, bakeCollision, usedIds, reach, nearestWalk, writeModule } from './kit.mjs';
import { importLqMap } from '../dev/import_lq_maps.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'src', 'data', 'maps');
const db = loadLqDb();
const problems = [];
const warn = (s) => console.warn('  warn: ' + s);

// ---------------------------------------------------------------- Willowmere (LQ as is + the Realms patch)
async function willowmere() {
  const z = await importLqMap('willowmere');
  // the west gate (LQ's X1 Orchard Lane gate, which the baseline import leaves out): a lamp, and the join to the Downs
  z.decor.push({ t: 'lamp_post', x: 1, y: 15, state: 1 });
  z.collision[15] = '#' + z.collision[15].slice(1);
  z.joins = [
    { x: 20, y: 31, w: 2, h: 1, to: 'valley', tx: 1, ty: 52, dir: 'right' },
    { x: 0, y: 16, w: 1, h: 2, to: 'downs', tx: 142, ty: 42, dir: 'left' },
  ];
  z.levels = [1, 1];
  z.areas = [
    { id: 'lantern_square', name: 'Lantern Square', x: 16, y: 14, w: 14, h: 10, safe: true },
    { id: 'south_gate', name: 'The South Gate', x: 14, y: 26, w: 14, h: 6, safe: true },
    { id: 'orchard_lane', name: 'Orchard Lane', x: 0, y: 12, w: 8, h: 8, safe: true },
  ];
  z.lanterns = [{ id: 'square', name: 'Lantern Square', x: 21, y: 19, post: [19, 22], bound: true }];
  z.npcs = [
    { npc: 'mael', x: 24, y: 18, dir: 'down' }, { npc: 'hob', x: 33, y: 13, dir: 'down' }, { npc: 'sloe', x: 36, y: 14, dir: 'left' },
    { npc: 'holt', x: 24, y: 29, dir: 'up' }, { npc: 'bram', x: 17, y: 29, dir: 'up' }, { npc: 'tess', x: 18, y: 27, dir: 'down' },
    { npc: 'hazel', x: 4, y: 16, dir: 'down' }, { npc: 'oren', x: 11, y: 16, dir: 'down' }, { npc: 'garrick', x: 29, y: 26, dir: 'down' },
    { npc: 'pell', x: 13, y: 26, dir: 'down' }, { npc: 'iris', x: 38, y: 23, dir: 'down' }, { npc: 'mira', x: 40, y: 23, dir: 'left' },
    { npc: 'nella', x: 42, y: 5, dir: 'right' }, { npc: 'lark', x: 26, y: 19, dir: 'left' }, { npc: 'wick', x: 19, y: 18, dir: 'right' },
    { npc: 'pip', x: 18, y: 14, dir: 'down' }, { npc: 'edda', x: 32, y: 5, dir: 'up' },
  ];
  z.spawns = []; z.nodes = [];
  z.signs = [{ id: 'west_gate', x: 1, y: 15, text: "ORCHARD LANE. WEST TO SHEPHERD'S DOWNS AND THORNFOLD." }];
  z.hooks = [];
  z.arrival = [20, 24];
  return z;
}

// ---------------------------------------------------------------- generated zones
function generated(mod) {
  const { map, realm } = mod.build(db);
  const collision = bakeCollision(map, db);
  const z = { ...map, source: `tools/maps/zone_${map.id}.mjs`, collision, ...realm };
  delete z.solids; delete z.open;
  return z;
}

function finish(z) {
  const isWalk = (x, y) => z.collision[y] && z.collision[y][x] === '.';
  const snap = (p, what) => {
    if (isWalk(p.x, p.y)) return;
    const n = nearestWalk(z, p.x, p.y, 4);
    if (!n) { problems.push(`${z.id}: ${what} at ${p.x},${p.y} has no walkable cell near`); return; }
    warn(`${z.id}: ${what} moved ${p.x},${p.y} -> ${n[0]},${n[1]}`);
    p.x = n[0]; p.y = n[1];
  };
  for (const s of z.spawns || []) snap(s, `spawn ${s.mob}`);
  for (const s of z.npcs || []) snap(s, `npc ${s.npc}`);
  for (const s of z.nodes || []) snap(s, `node ${s.id}`);
  for (const s of z.lanterns || []) snap(s, `lantern ${s.id}`);
  for (const s of z.hooks || []) snap(s, `hook ${s.id}`);
  const [ax, ay] = z.arrival;
  if (!isWalk(ax, ay)) problems.push(`${z.id}: arrival ${ax},${ay} not walkable`);
  const seen = reach(z, ax, ay);
  const ok = (x, y) => seen[y * z.w + x] === 1;
  for (const [k, list] of [['spawn', z.spawns], ['npc', z.npcs], ['node', z.nodes], ['lantern', z.lanterns], ['hook', z.hooks]]) {
    for (const p of list || []) if (!ok(p.x, p.y)) problems.push(`${z.id}: ${k} ${p.mob || p.npc || p.id} at ${p.x},${p.y} is not reachable from the arrival`);
  }
  for (const a of z.areas || []) {
    let any = false;
    for (let y = a.y; y < a.y + a.h && !any; y++) for (let x = a.x; x < a.x + a.w; x++) if (x < z.w && y < z.h && ok(x, y)) { any = true; break; }
    if (!any) problems.push(`${z.id}: area ${a.id} has no reachable cell`);
  }
  let walk = 0, reached = 0;
  for (let y = 0; y < z.h; y++) for (let x = 0; x < z.w; x++) if (isWalk(x, y)) { walk++; if (ok(x, y)) reached++; }
  console.log(`${z.id}: ${z.w}x${z.h}  walkable ${walk}, reachable ${reached} (${(100 * reached / walk).toFixed(1)}%)  spawns ${(z.spawns || []).length} npcs ${(z.npcs || []).length} nodes ${(z.nodes || []).length}`);
  return z;
}

const gens = [];
for (const id of ['valley', 'downs', 'moor']) {
  if (!fs.existsSync(path.join(path.dirname(fileURLToPath(import.meta.url)), `zone_${id}.mjs`))) { console.warn(`  (no zone_${id}.mjs yet)`); continue; }
  gens.push(generated(await import(`./zone_${id}.mjs`)));
}
const zones = [await willowmere(), ...gens].map(finish);

// joins land on walkable, reachable cells on the other side
const byId = Object.fromEntries(zones.map((z) => [z.id, z]));
for (const z of zones) for (const j of z.joins) {
  const o = byId[j.to];
  if (!o) continue;
  if (!(o.collision[j.ty] && o.collision[j.ty][j.tx] === '.')) problems.push(`${z.id} join -> ${j.to} ${j.tx},${j.ty} lands on '${o.collision[j.ty] && o.collision[j.ty][j.tx]}'`);
  if (!o.joins.some((k) => k.to === z.id)) problems.push(`${z.id} join -> ${j.to}: no join back`);
}

if (problems.length) {
  console.log('BUILD_WORLD_FAIL\n  ' + problems.join('\n  '));
  process.exitCode = 1;
}

// ---------------------------------------------------------------- write
const ids = new Set();
for (const z of zones) {
  usedIds(z, ids);
  const header = z.id === 'willowmere'
    ? `// GENERATED by tools/maps/build_world.mjs from Lexicon Quest's willowmere (READ ONLY source) plus the Realms patch. Do not hand-edit.\n// Zone shape: docs/CONTRACTS.md section 6.`
    : `// GENERATED by tools/maps/build_world.mjs from tools/maps/zone_${z.id}.mjs. Do not hand-edit: change the generator and re-run.\n// Zone shape: docs/CONTRACTS.md section 6.`;
  writeModule(path.join(OUT, `${z.id}.js`), header, z);
}
const T = db.tiles;
const pick = (obj) => Object.fromEntries(Object.entries(obj).filter(([k]) => ids.has(k) || ids.has(`${k}_top`) || ids.has(`${k}_face`)));
const trimmed = {
  version: T.version, tileSize: T.tileSize,
  source: 'LexiconQuest next/assets/tiles/tiles.json + x1_tiles.json (merged as LQ packs.js does), trimmed by tools/maps/build_world.mjs',
  collisionCodes: T.collisionCodes, terrainOrder: T.terrainOrder,
  terrains: pick(T.terrains), walls: pick(T.walls), tiles: pick(T.tiles), objects: pick(T.objects),
};
const sheets = new Set();
for (const k of ['terrains', 'walls', 'tiles', 'objects']) for (const v of Object.values(trimmed[k])) sheets.add(v.sheet);
const tilesOut = path.join(ROOT, 'assets', 'tiles');
fs.writeFileSync(path.join(tilesOut, 'tiles.json'), JSON.stringify(trimmed));
for (const s of sheets) fs.copyFileSync(path.join(LQ, 'assets', 'tiles', s), path.join(tilesOut, s));
for (const f of ['props.json', 'props.png']) fs.copyFileSync(path.join(LQ, 'assets', 'sprites', f), path.join(tilesOut, f));
console.log(`tiles.json: ${Object.keys(trimmed.terrains).length} terrains, ${Object.keys(trimmed.walls).length} walls, ${Object.keys(trimmed.tiles).length} tiles, ${Object.keys(trimmed.objects).length} objects; sheets ${[...sheets].join(', ')}`);
console.log(problems.length ? `BUILD_WORLD: ${problems.length} problems` : 'BUILD_WORLD_OK');
